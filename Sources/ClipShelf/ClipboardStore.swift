            switch self {
            case .written: "已复制"
            case .imageUnavailable: "无法读取原图片。请右键卡片，选择「选取图片文件…」。"
            case .imagePendingSync: "图片尚未同步"
            case .clipboardChanged: "剪贴板已变化，本次操作已取消。"
            case .failed: "复制失败"
            case .cancelled: nil
            }
        }
    }

